// @vitest-environment node
import { describe, expect, it } from "vitest"
import openapiTS, { astToString } from "openapi-typescript"
// the committed files, read by Vite (no file system API in the app's types)
import document from "./openapi.json"
import committed from "./schema.d.ts?raw"

// the generator's own banner, as `openapi-typescript` (the CLI, `npm run api`) writes it
const BANNER = "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n"

describe("the API types (#590)", () => {
	it("are generated from the committed OpenAPI document: run `npm run api` when this fails", async () => {
		const generated = BANNER + astToString(await openapiTS(structuredClone(document) as Parameters<typeof openapiTS>[0]))
		expect(committed.replace(/\r\n/g, "\n")).toBe(generated)
	})
})
